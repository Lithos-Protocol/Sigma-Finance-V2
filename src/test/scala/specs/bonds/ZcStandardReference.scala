package org.lithosprotocol.sigmafi
package specs.bonds

import ksingh.sigmabonds.standard.{StandardContracts, StandardPins}
import org.ergoplatform.appkit.{Address, BlockchainContext, NetworkType}
import scorex.crypto.hash.Blake2b256
import scorex.util.encode.Base16
import specs.harness.ContractSpecBase

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}

/**
 * Generates the ZC Standard pins from the compiler: the classpath resource the client loads its trees
 * from (`StandardPins.SourcePath`), and a reference document for people. `ZcStandardProbeSpec` fails
 * while either differs from what the compiler produces now.
 *
 *   sbt "Test / runMain org.lithosprotocol.sigmafi.specs.bonds.ZcStandardReference --write"
 */
object ZcStandardReference extends ContractSpecBase {
  val Document = "docs/ZC_STANDARD_REFERENCE.md"

  private def hex(bytes: Array[Byte]): String = Base16.encode(bytes)
  private def hash(bytes: Array[Byte]): String = hex(Blake2b256.hash(bytes))
  private def read(path: String): String =
    if (Files.exists(Paths.get(path))) new String(Files.readAllBytes(Paths.get(path)), UTF_8).replace("\r\n", "\n")
    else ""

  def pins(ctx: BlockchainContext): String = StandardPins.render(ZcStandardSpecBase.compiled(ctx))

  def document(ctx: BlockchainContext): String = {
    val set = ZcStandardSpecBase.compiled(ctx)
    val b = new StringBuilder
    def line(s: String = ""): Unit = { b.append(s); b.append('\n') }

    line("# ZC Standard compiled reference")
    line()
    line("Generated by `sbt \"Test / runMain org.lithosprotocol.sigmafi.specs.bonds.ZcStandardReference --write\"`;")
    line("do not edit. `ZcStandardProbeSpec` fails while this file or the pinned trees in")
    line(s"`${StandardPins.SourcePath}` differ from the compiler's output. The client builds with those pinned")
    line("trees, never with a fresh compile, so a compiler upgrade cannot silently move an address or a hash")
    line("another contract pins.")
    line()
    line("Compiled offline through `StandardContracts.compile` with the repository's V6 mock context. Every tree")
    line("is ErgoTree version 3 with the size bit set, so deployment needs the 6.0 soft fork active.")
    line()
    line("- **Tree hash**: blake2b256 of the serialized ErgoTree. It is what another contract pins")
    line("  (`CONST_VAULT_HASH`, `CONST_BOND_HASH`, ...) and what a box's script-hash register holds.")
    line("- **Template hash**: blake2b256 of the tree without its constants. Every market of one contract shares")
    line("  it, so an indexed node lists all markets at once by template hash.")
    line("- **Expression hash**: for scripts run through `executeFromVar`, blake2b256 of the expression bytes")
    line("  that go in the context variable. A bond's R8, an offer's R6 and an ask's R6 commit to it.")
    line()
    line("## Contracts")
    line()
    line("| Contract | Market | Bytes | Tree hash | Template hash |")
    line("|---|---|---:|---|---|")
    set.entries.filterNot(_.expression).foreach { e =>
      val t = e.contract.ergoTree
      line(s"| ${e.name} | ${e.market.fold("all")(_.name)} | ${t.bytes.length} | `${hash(t.bytes)}` | `${hash(t.template)}` |")
    }
    line()
    line("## Expressions")
    line()
    line("| Expression | Market | Expression bytes | Expression hash |")
    line("|---|---|---:|---|")
    set.entries.filter(_.expression).foreach { e =>
      line(s"| ${e.name} | ${e.market.fold("all")(_.name)} | ${e.contract.valueBytes.length} | `${hex(e.contract.hashedValueBytes)}` |")
    }
    line()
    line("## Addresses")
    line()
    line("Expressions have no address: nothing is ever locked under them.")
    line()
    set.entries.filterNot(_.expression).foreach { e =>
      line(s"### ${e.label}")
      line()
      line("```text")
      line("mainnet " + Address.fromErgoTree(e.contract.ergoTree, NetworkType.MAINNET).toString)
      line("testnet " + Address.fromErgoTree(e.contract.ergoTree, NetworkType.TESTNET).toString)
      line("```")
      line()
    }
    b.toString
  }

  def check(ctx: BlockchainContext): Unit = {
    val hint = "run Test / runMain org.lithosprotocol.sigmafi.specs.bonds.ZcStandardReference --write"
    require(read(StandardPins.SourcePath) == pins(ctx), s"the pinned ZC Standard trees are stale; $hint")
    require(read(Document) == document(ctx), s"$Document is stale; $hint")
  }

  def main(args: Array[String]): Unit = {
    require(args.toSeq == Seq("--write") || args.toSeq == Seq("--check"), "use --write or --check")
    withCtx { ctx =>
      if (args.head == "--write") {
        Files.createDirectories(Paths.get(StandardPins.SourcePath).getParent)
        Files.write(Paths.get(StandardPins.SourcePath), pins(ctx).getBytes(UTF_8))
        Files.write(Paths.get(Document), document(ctx).getBytes(UTF_8))
        println(s"Generated ${StandardPins.SourcePath} and $Document")
      } else {
        check(ctx)
        println(s"Verified ${StandardPins.SourcePath} and $Document")
      }
    }
  }
}
